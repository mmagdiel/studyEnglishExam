// Generates dist/sw.js after `astro build`.
// The service worker precaches every built file (pages, scripts, styles, icons)
// so the installed app opens and works offline. The cache name is a hash of the
// build output, so each deploy replaces the old cache.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

async function listFiles(dir) {
	const entries = await readdir(dir, { withFileTypes: true });
	const files = await Promise.all(
		entries.map((e) => (e.isDirectory() ? listFiles(join(dir, e.name)) : [join(dir, e.name)])),
	);
	return files.flat();
}

/** "topics/adverbs/index.html" → "/topics/adverbs/", "index.html" → "/" */
function toUrl(path) {
	const url = "/" + path.split(sep).join("/");
	return url.endsWith("/index.html") ? url.slice(0, -"index.html".length) : url;
}

const SKIP = new Set(["sw.js", "favicon.ico"]);

/** @returns {import("astro").AstroIntegration} */
export default function pwa() {
	return {
		name: "grammar-master-pwa",
		hooks: {
			"astro:build:done": async ({ dir, logger }) => {
				const root = fileURLToPath(dir);
				const files = (await listFiles(root))
					.map((f) => relative(root, f))
					.filter((f) => !SKIP.has(f) && !f.split(sep).pop().startsWith("."))
					.sort();

				const hash = createHash("sha256");
				for (const f of files) hash.update(f).update(await readFile(join(root, f)));
				const version = hash.digest("hex").slice(0, 12);

				const urls = files.map(toUrl);
				await writeFile(join(root, "sw.js"), serviceWorker(version, urls));
				logger.info(`sw.js: ${urls.length} files precached (cache ${version})`);
			},
		},
	};
}

const serviceWorker = (version, urls) => `// Generated by integrations/pwa.mjs, do not edit.
const CACHE = "grammar-master-${version}";
const PRECACHE = ${JSON.stringify(urls, null, 1)};

self.addEventListener("install", (event) => {
	event.waitUntil(
		caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
	);
});

self.addEventListener("activate", (event) => {
	event.waitUntil(
		caches
			.keys()
			.then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
			.then(() => self.clients.claim()),
	);
});

// "/test" and "/test/" are the same page; the cache stores the "/test/" form.
function cacheKey(url) {
	const u = new URL(url);
	u.search = "";
	u.hash = "";
	if (!u.pathname.endsWith("/") && !u.pathname.split("/").pop().includes(".")) u.pathname += "/";
	return u.href;
}

self.addEventListener("fetch", (event) => {
	const { request } = event;
	if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;

	if (request.mode === "navigate") {
		// Pages: try the network first so new deploys show up, fall back to the cache offline.
		event.respondWith(
			fetch(request).catch(async () => {
				const cache = await caches.open(CACHE);
				return (
					(await cache.match(cacheKey(request.url))) ||
					(await cache.match("/404.html")) ||
					Response.error()
				);
			}),
		);
		return;
	}

	// Scripts, styles, icons: serve from the cache, fetch anything missing.
	event.respondWith(
		caches.match(request, { ignoreSearch: true }).then((hit) => hit || fetch(request)),
	);
});
`;
